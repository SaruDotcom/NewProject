function normalizeBusinessType(type) {
  if (!type) return 'CLOTHING';
  const upper = String(type).trim().toUpperCase();

  if (upper === 'CLOTHING') return 'CLOTHING';
  if (upper === 'COSMETICS') return 'COSMETICS';
  if (upper === 'GENERAL_STORE') return 'GENERAL_STORE';
  if (upper === 'FOOTWEAR') return 'FOOTWEAR';
  if (upper === 'ELECTRONICS') return 'ELECTRONICS';

  // Check specific categories before clothing to prevent 'footwear' matching 'wear'
  if (/FOOTWEAR|SHOE|SANDAL|SLIPPER|SNEAKER|BOOT/.test(upper)) return 'FOOTWEAR';
  if (/COSMETIC|BEAUTY|SKINCARE|MAKEUP|SALON|PERSONAL\s*CARE/.test(upper)) return 'COSMETICS';
  if (/GENERAL|KIRANA|GROCERY|FMCG|STAPLE|PROVISION|SUPERMARKET/.test(upper)) return 'GENERAL_STORE';
  if (/ELECTRONIC|GADGET|APPLIANCE|TECH|MOBILE|COMPUTER/.test(upper)) return 'ELECTRONICS';
  if (/CLOTH|APPAREL|FASHION|GARMENT|ETHNIC|KURTI|SAREE|LEHENGA|DRESS|\bWEAR\b/.test(upper)) return 'CLOTHING';

  return 'OTHER';
}

function getPresetsForType(type) {
  const normalized = normalizeBusinessType(type);
  return BUSINESS_TYPE_BANNERS[normalized] || BUSINESS_TYPE_BANNERS.CLOTHING;
}

